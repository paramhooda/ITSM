// ---------------------------------------------------------------- resolution suggestions

const resolutionSchema = z.object({ suggestions: z.array(z.object({ source: z.enum(['ticket', 'kb']), ref: z.string().max(60), title: z.string().max(300), steps: z.array(z.string().max(400)).max(8) })).max(6) });

const splitSteps = (text: string, max = 6) =>
  text
    .split(/\r?\n+|(?<=[.!?])\s+(?=[A-Z0-9])/)
    .map((s) => s.replace(/^[-*\d.)\s]+/, '').trim())
    .filter((s) => s.length > 8)
    .slice(0, max);

export async function resolutionSuggestions(who: Who, ticketId: string) {
  const s = asSteps(who);
  const g = await s.tx(async (ctx) => {
    await assertFeature(ctx, 'resolution');
    const { row } = await readTicket(ctx, ticketId);
    const sim = await similarTickets(ctx, ticketId);
    const resolved = sim.items.filter((x) => x.resolutionNotes && x.resolutionNotes.trim().length > 10).slice(0, 5).map((x) => ({ ...x, link: ticketLink(ctx, x.id) }));
    const kb = await kbSuggest(ctx, { q: row.title, customerId: row.customerId, serviceId: row.serviceId ?? undefined, limit: 4 });
    const articles: { id: string; number: string; title: string; summary: string | null; body: string }[] = [];
    for (const a of kb.items.slice(0, 3)) {
      try {
        const full = await getArticle(ctx, a.id, { noView: true });
        articles.push({ id: a.id, number: a.number, title: a.title, summary: a.summary, body: trunc(full.body, 2500) });
      } catch {
        /* not visible */
      }
    }
    return { row, resolved, articles };
  });
  const { row, resolved, articles } = g;
  const fallback = {
    suggestions: [
      ...resolved.map((x) => ({ source: 'ticket' as const, ref: x.number, title: x.title, steps: splitSteps(x.resolutionNotes!), link: x.link })),
      ...articles.map((a) => ({ source: 'kb' as const, ref: a.number, title: a.title, steps: splitSteps(a.body || a.summary || '', 5), link: `/knowledge/${a.id}` })),
    ].slice(0, 5),
  };
  const llm = resolved.length || articles.length
    ? await llmJson(RESOLUTION_SYSTEM, JSON.stringify({ ticket: { number: row.number, title: row.title, description: trunc(row.description, 2000) }, resolvedTickets: resolved.map((x) => ({ number: x.number, title: x.title, resolutionNotes: trunc(x.resolutionNotes, 1200) })), articles }), (v) => resolutionSchema.parse(v), { maxTokens: 1200 })
    : null;
  const links = new Map<string, string>([...resolved.map((x) => [x.number, x.link] as const), ...articles.map((a) => [a.number, `/knowledge/${a.id}`] as const)]);
  const payload = llm ? { suggestions: llm.data.suggestions.map((x) => ({ ...x, link: links.get(x.ref) ?? null })) } : fallback;
  return s.tx(async (ctx) => {
    const suggestionId = await store(ctx, { customerId: row.customerId, entityType: 'ticket', entityId: row.id, kind: 'resolution', payload, rationale: llm ? 'Synthesised from resolved similar tickets and knowledge articles' : 'Extracted from resolution notes of similar tickets and matching articles' });
    return { suggestionId, aiGenerated: !!llm, ...payload, sources: { resolvedTickets: resolved.length, articles: articles.length } };
  });
}

