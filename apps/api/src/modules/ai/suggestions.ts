export const recommendAssignment = (who: Who, ticketId: string) => asSteps(who).tx((ctx) => recommendAssignmentIn(ctx, ticketId));

async function recommendAssignmentIn(ctx: Ctx, ticketId: string) {
  await assertFeature(ctx, 'assign');
  const { row, detail } = await readTicket(ctx, ticketId);
  if (isCustomerUser(ctx)) throw new ForbiddenError();
  const rule = await evaluateAssignment(ctx.tx, { ticketType: row.type, categoryId: row.categoryId, serviceId: row.serviceId, customerId: row.customerId, priorityId: row.priorityId, domain: row.domain, sourceId: row.sourceId, contractTeamId: null });
  const since = new Date(Date.now() - 90 * 86_400_000);
  // Engineers who resolved similar work for this customer recently, with their current open load.
  const candidates = await ctx.tx.execute(sql`
    WITH resolved AS (
      SELECT t.assignee_id AS user_id,
             count(*) FILTER (WHERE t.customer_id = ${row.customerId}::uuid)::int AS same_customer,
             count(*) FILTER (WHERE ${row.categoryId ? sql`t.category_id = ${row.categoryId}::uuid` : sql`false`})::int AS same_category,
             count(*)::int AS total
      FROM tickets t
      WHERE t.assignee_id IS NOT NULL AND t.resolved_at >= ${since} AND t.type = ${row.type}
      GROUP BY t.assignee_id
    ), load AS (
      SELECT t.assignee_id AS user_id, count(*)::int AS open_load
      FROM tickets t JOIN config_options s ON s.id = t.status_id
      WHERE t.assignee_id IS NOT NULL AND s.status_category IN ('new','open','pending')
      GROUP BY t.assignee_id
    )
    SELECT u.id, u.name, u.email, coalesce(r.same_customer, 0) AS "sameCustomer", coalesce(r.same_category, 0) AS "sameCategory", coalesce(r.total, 0) AS "resolved90d", coalesce(l.open_load, 0) AS "openLoad",
           (SELECT array_agg(tm.team_id) FROM team_members tm WHERE tm.user_id = u.id) AS "teamIds"
    FROM users u
    LEFT JOIN resolved r ON r.user_id = u.id
    LEFT JOIN load l ON l.user_id = u.id
    WHERE u.user_type = 'msp' AND u.status = 'active'
    ORDER BY coalesce(r.same_category, 0) + coalesce(r.same_customer, 0) * 2 DESC, coalesce(l.open_load, 0) ASC, coalesce(r.total, 0) DESC
    LIMIT 25`);
  const rows = candidates.rows as { id: string; name: string; email: string; sameCustomer: number; sameCategory: number; resolved90d: number; openLoad: number; teamIds: string[] | null }[];
  const teams = await ctx.tx.select({ id: schema.teams.id, key: schema.teams.key, name: schema.teams.name }).from(schema.teams).where(eq(schema.teams.isActive, true));
  const teamOf = (id: string | null | undefined) => teams.find((t) => t.id === id) ?? null;

  let teamId: string | null = rule.teamId;
  let userId: string | null = rule.userId;
  const reasons: string[] = [];
  if (rule.source === 'rule') reasons.push(`Assignment rule "${rule.ruleName}" matches this ticket`);
  else if (rule.source === 'service') reasons.push(`Default team of service ${detail.service?.name ?? ''}`);
  if (!teamId && detail.cis.length) {
    const [ci] = await ctx.tx.select({ ownerTeamId: schema.cis.ownerTeamId }).from(schema.cis).where(eq(schema.cis.id, detail.cis[0]!.id)).limit(1);
    if (ci?.ownerTeamId) {
      teamId = ci.ownerTeamId;
      reasons.push(`Owner team of the affected CI ${detail.cis[0]!.name}`);
    }
  }
  if (!userId) {
    const pool = rows.filter((r) => (r.sameCustomer > 0 || r.sameCategory > 0) && (!teamId || (r.teamIds ?? []).includes(teamId)));
    const pick = pool[0] ?? (teamId ? rows.filter((r) => (r.teamIds ?? []).includes(teamId!)).sort((a, b) => a.openLoad - b.openLoad)[0] : undefined);
    if (pick) {
      userId = pick.id;
      if (pick.sameCategory || pick.sameCustomer) reasons.push(`${pick.name} resolved ${pick.sameCategory} ticket(s) in this category and ${pick.sameCustomer} for this customer in the last 90 days, with ${pick.openLoad} open ticket(s) now`);
      else reasons.push(`${pick.name} has the lowest open load (${pick.openLoad}) in the team`);
      if (!teamId && pick.teamIds?.length) teamId = pick.teamIds[0]!;
    }
  }
  const user = userId ? (rows.find((r) => r.id === userId) ?? (await ctx.tx.select({ id: schema.users.id, name: schema.users.name, email: schema.users.email }).from(schema.users).where(eq(schema.users.id, userId)).limit(1))[0]) : null;
  const team = teamOf(teamId);
  const payload = {
    teamKey: team?.key ?? null,
    teamId: team?.id ?? null,
    teamName: team?.name ?? null,
    userId: user?.id ?? null,
    userName: user?.name ?? null,
    rationale: reasons.join('. ') || 'No rule, service default or recent resolver found; assign manually.',
    source: rule.source,
    alternatives: rows.slice(0, 5).map((r) => ({ userId: r.id, name: r.name, resolvedSimilar: r.sameCategory, resolvedForCustomer: r.sameCustomer, openLoad: r.openLoad })),
    current: { teamId: row.assignedTeamId, assigneeId: row.assigneeId },
  };
  const suggestionId = await store(ctx, { customerId: row.customerId, entityType: 'ticket', entityId: row.id, kind: 'assignment', payload, rationale: payload.rationale, confidence: user ? 70 : team ? 50 : 20 });
  return { suggestionId, aiGenerated: false, ...payload };
}

