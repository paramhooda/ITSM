const impactSchema = z.object({ riskSummary: z.string().min(10).max(2000), riskLevel: z.enum(['low', 'medium', 'high']), recommendations: z.array(z.string().max(300)).max(6) });

export async function changeImpact(who: Who, changeId: string) {
  const s = asSteps(who);
  const g = await s.tx((ctx) => gatherChangeImpact(ctx, changeId));
  const { row, data, fallback, affected, dependents, services, otherChanges } = g;
  const llm = await llmJson(IMPACT_SYSTEM, JSON.stringify(data), (v) => impactSchema.parse(v), { maxTokens: 600 });
  const analysis = llm?.data ?? fallback;
  return s.tx(async (ctx) => {
    const suggestionId = await store(ctx, { customerId: row.customerId, entityType: 'ticket', entityId: row.id, kind: 'change_impact', payload: { ...analysis, affectedCis: affected.map((a) => a.name), dependents: dependents.size, businessServices: [...services], otherChanges: otherChanges.map((o) => o.number) }, rationale: analysis.riskSummary });
    return { suggestionId, aiGenerated: !!llm, ...data, ...analysis };
  });
}

async function gatherChangeImpact(ctx: Ctx, changeId: string) {
  await assertFeature(ctx, 'change_impact');
  const { row, detail } = await readTicket(ctx, changeId);
  if (row.type !== 'change') throw new ValidationError('Impact analysis is only available for change records');
  ctx.require('changes:manage', row.customerId);
  const change = detail.change;
  const affected: { id: string; name: string; type: string | null; criticality: string | null; dependents: number; businessServices: string[]; openTickets: number }[] = [];
  const dependents = new Map<string, { name: string; type: string; criticality: string; via: string; from: string }>();
  const services = new Set<string>();
  const openTickets = new Map<string, { number: string; title: string; status: string; link: string }>();
  for (const ci of detail.cis.slice(0, 10)) {
    try {
      const imp = await ciImpact(ctx, ci.id);
      imp.dependents.forEach((d) => dependents.set(d.id, { name: d.name, type: d.typeName, criticality: d.criticality, via: d.via, from: ci.name }));
      imp.businessServices.forEach((b) => services.add(b.name));
      imp.openTickets.forEach((t) => openTickets.set(t.id, { number: t.number, title: t.title, status: t.status, link: ticketLink(ctx, t.id) }));
      affected.push({ id: ci.id, name: ci.name, type: imp.root.typeName, criticality: imp.root.criticality, dependents: imp.dependents.length, businessServices: imp.businessServices.map((b) => b.name), openTickets: imp.openTickets.length });
    } catch {
      affected.push({ id: ci.id, name: ci.name, type: null, criticality: null, dependents: 0, businessServices: [], openTickets: 0 });
    }
  }
  // Other changes of the customer overlapping the scheduled window (± 1 day when no window is set).
  const start = change?.scheduledStart ? new Date(change.scheduledStart) : new Date();
  const end = change?.scheduledEnd ? new Date(change.scheduledEnd) : new Date(start.getTime() + 86_400_000);
  const windowFrom = new Date(start.getTime() - 86_400_000);
  const windowTo = new Date(end.getTime() + 86_400_000);
  const overlapping = await ctx.tx
    .select({ id: schema.tickets.id, number: schema.tickets.number, title: schema.tickets.title, scheduledStart: schema.changeDetails.scheduledStart, scheduledEnd: schema.changeDetails.scheduledEnd, statusId: schema.tickets.statusId })
    .from(schema.changeDetails)
    .innerJoin(schema.tickets, eq(schema.tickets.id, schema.changeDetails.ticketId))
    .where(and(eq(schema.tickets.customerId, row.customerId), ne(schema.tickets.id, row.id), isNotNull(schema.changeDetails.scheduledStart), sql`${schema.changeDetails.scheduledStart} <= ${windowTo}`, sql`coalesce(${schema.changeDetails.scheduledEnd}, ${schema.changeDetails.scheduledStart} + interval '4 hours') >= ${windowFrom}`))
    .orderBy(schema.changeDetails.scheduledStart)
    .limit(10);
  const statusRows = overlapping.length ? await ctx.tx.select({ id: schema.configOptions.id, label: schema.configOptions.label, category: schema.configOptions.statusCategory }).from(schema.configOptions).where(inArray(schema.configOptions.id, overlapping.map((o) => o.statusId))) : [];
  const otherChanges = overlapping
    .map((o) => ({ id: o.id, number: o.number, title: o.title, scheduledStart: o.scheduledStart?.toISOString() ?? null, scheduledEnd: o.scheduledEnd?.toISOString() ?? null, status: statusRows.find((s) => s.id === o.statusId)?.label ?? null, statusCategory: statusRows.find((s) => s.id === o.statusId)?.category ?? null, link: ticketLink(ctx, o.id) }))
    .filter((o) => !['closed', 'cancelled'].includes(o.statusCategory ?? ''));

  const data = {
    change: { number: row.number, title: row.title, type: change?.changeType ?? null, risk: change?.risk?.label ?? null, scheduledStart: change?.scheduledStart?.toISOString() ?? null, scheduledEnd: change?.scheduledEnd?.toISOString() ?? null, downtimeExpectedMinutes: change?.downtimeExpectedMinutes ?? null, backoutPlan: !!change?.backoutPlan, testPlan: !!change?.testPlan, implementationPlan: trunc(change?.implementationPlan, 600) },
    affectedCis: affected,
    downstream: [...dependents.values()].slice(0, 60),
    businessServices: [...services],
    openTickets: [...openTickets.values()].slice(0, 30),
    otherChanges,
  };
  const critical = [...dependents.values()].filter((d) => d.criticality === 'critical' || d.criticality === 'high').length + affected.filter((a) => a.criticality === 'critical' || a.criticality === 'high').length;
  const heuristicLevel: 'low' | 'medium' | 'high' = services.size > 0 || critical > 0 || (change?.changeType === 'emergency') ? 'high' : dependents.size > 3 || openTickets.size > 0 || otherChanges.length > 0 ? 'medium' : 'low';
  const fallback: z.infer<typeof impactSchema> = {
    riskLevel: heuristicLevel,
    riskSummary: `${row.number} touches ${affected.length} configuration item(s)${affected.length ? ` (${affected.map((a) => a.name).join(', ')})` : ''} with ${dependents.size} downstream dependent CI(s)${services.size ? ` and ${services.size} business service(s): ${[...services].join(', ')}` : ''}. ${openTickets.size ? `${openTickets.size} open ticket(s) already reference the affected items. ` : ''}${otherChanges.length ? `${otherChanges.length} other change(s) are scheduled in the same window (${otherChanges.map((o) => o.number).join(', ')}). ` : ''}${change?.backoutPlan ? 'A backout plan is documented.' : 'No backout plan is documented.'}`,
    recommendations: [
      !change?.backoutPlan ? 'Document a backout plan before approval' : null,
      !change?.testPlan ? 'Add a test / verification plan' : null,
      services.size ? 'Notify business-service owners and schedule within an agreed maintenance window' : null,
      otherChanges.length ? 'Coordinate with the overlapping changes to avoid compounding outages' : null,
      openTickets.size ? 'Review open tickets on the affected CIs; consider linking them to this change' : null,
      !change?.scheduledStart ? 'Set a scheduled start and end' : null,
    ].filter(Boolean) as string[],
  };
  return { row, data, fallback, affected, dependents, services, otherChanges };
}

// ---------------------------------------------------------------- problem clusters

const clusterNamesSchema = z.object({ clusters: z.array(z.object({ key: z.string(), title: z.string().max(120) })).max(60) });
const STOP = new Set(['the', 'a', 'an', 'on', 'in', 'at', 'for', 'to', 'of', 'and', 'or', 'is', 'are', 'with', 'from', 'not', 'no', 'has', 'have', 'been', 'after', 'by', 'issue', 'problem', 'error', 'ticket', 'please', 'again', 'still']);
const tokens = (title: string) => new Set(title.toLowerCase().replace(/[^a-z0-9\s-]/g, ' ').split(/\s+/).filter((w) => w.length > 2 && !STOP.has(w) && !/^\d+$/.test(w)));
const jaccard = (a: Set<string>, b: Set<string>) => {
  if (!a.size || !b.size) return 0;
  let inter = 0;
  for (const x of a) if (b.has(x)) inter++;
  return inter / (a.size + b.size - inter);
};

export async function problemClusters(who: Who, opts: { days?: number; customerId?: string; minCount?: number } = {}) {
  const s = asSteps(who);
  const g = await s.tx((ctx) => gatherProblemClusters(ctx, opts));
  const { days, minCount, rows, top } = g;
  let aiGenerated = false;
  if (top.length) {
    const llm = await llmJson(CLUSTER_SYSTEM, JSON.stringify({ clusters: top.map((c) => ({ key: c.key, customer: c.customerName, category: c.categoryLabel, ci: c.ciName, count: c.count, titles: c.sampleTickets.map((t) => t.title) })) }), (v) => clusterNamesSchema.parse(v), { maxTokens: 1500 });
    if (llm) {
      const names = new Map(llm.data.clusters.map((c) => [c.key, c.title]));
      for (const c of top) if (names.get(c.key)) c.suggestedTitle = names.get(c.key)!;
      aiGenerated = true;
    }
  }
  return { days, minCount, aiGenerated, totalIncidents: rows.length, clusters: top };
}

async function gatherProblemClusters(ctx: Ctx, opts: { days?: number; customerId?: string; minCount?: number }) {
  await assertFeature(ctx, 'problem_clusters');
  if (isCustomerUser(ctx)) throw new ForbiddenError();
  ctx.require('tickets:read');
  const days = opts.days ?? 30;
  const minCount = opts.minCount ?? 3;
  if (opts.customerId) ctx.requireCustomer(opts.customerId);
  const conds = [sql`t.type = 'incident'`, sql`t.created_at >= now() - make_interval(days => ${days})`];
  if (opts.customerId) conds.push(sql`t.customer_id = ${opts.customerId}::uuid`);
  if (!ctx.can('soc:read')) conds.push(sql`t.domain <> 'soc'`);
  conds.push(sql`NOT EXISTS (SELECT 1 FROM ticket_links l JOIN tickets p ON p.id IN (l.target_ticket_id, l.source_ticket_id) WHERE (l.source_ticket_id = t.id OR l.target_ticket_id = t.id) AND p.type = 'problem')`);
  const res = await ctx.tx.execute(sql`
    SELECT t.id, t.number, t.title, t.created_at AS "createdAt", t.resolved_at AS "resolvedAt",
           t.customer_id AS "customerId", c.name AS "customerName", t.category_id AS "categoryId", co.label AS "categoryLabel",
           t.primary_ci_id AS "primaryCiId", ci.name AS "ciName", s.label AS "status", s.status_category AS "statusCategory", t.service_id AS "serviceId", sv.name AS "serviceName"
    FROM tickets t
    JOIN customers c ON c.id = t.customer_id
    JOIN config_options s ON s.id = t.status_id
    LEFT JOIN config_options co ON co.id = t.category_id
    LEFT JOIN cis ci ON ci.id = t.primary_ci_id
    LEFT JOIN services sv ON sv.id = t.service_id
    WHERE ${sql.join(conds, sql` AND `)}
    ORDER BY t.created_at DESC
    LIMIT 3000`);
  type Row = { id: string; number: string; title: string; createdAt: string; resolvedAt: string | null; customerId: string; customerName: string; categoryId: string | null; categoryLabel: string | null; primaryCiId: string | null; ciName: string | null; status: string; statusCategory: string; serviceId: string | null; serviceName: string | null };
  const rows = res.rows as Row[];
  // 1) group by customer + category + primary CI
  const groups = new Map<string, Row[]>();
  for (const r of rows) {
    const k = `${r.customerId}|${r.categoryId ?? '-'}|${r.primaryCiId ?? '-'}`;
    groups.set(k, [...(groups.get(k) ?? []), r]);
  }
  // 2) within each group, cluster by title token overlap
  const clusters: { key: string; customerId: string; customerName: string; categoryLabel: string | null; ciName: string | null; serviceName: string | null; count: number; openCount: number; firstAt: string; lastAt: string; commonTerms: string[]; suggestedTitle: string; sampleTickets: { id: string; number: string; title: string; status: string; createdAt: string; link: string }[] }[] = [];
  for (const [gk, members] of groups) {
    if (members.length < minCount) continue;
    const buckets: { tokens: Set<string>; items: Row[] }[] = [];
    for (const m of members) {
      const tk = tokens(m.title);
      const hit = buckets.find((b) => jaccard(b.tokens, tk) >= 0.34);
      if (hit) {
        hit.items.push(m);
        tk.forEach((t) => hit.tokens.add(t));
      } else buckets.push({ tokens: new Set(tk), items: [m] });
    }
    // small buckets fold back into the group-level cluster when the CI or category already ties them together
    const big = buckets.filter((b) => b.items.length >= minCount);
    const rest = buckets.filter((b) => b.items.length < minCount).flatMap((b) => b.items);
    const finalBuckets = big.map((b) => b.items);
    if (rest.length >= minCount && (members[0]!.primaryCiId || members[0]!.categoryId)) finalBuckets.push(rest);
    for (const items of finalBuckets) {
      const freq = new Map<string, number>();
      for (const it of items) for (const t of tokens(it.title)) freq.set(t, (freq.get(t) ?? 0) + 1);
      const common = [...freq.entries()].filter(([, n]) => n >= Math.max(2, Math.ceil(items.length / 2))).sort((a, b) => b[1] - a[1]).slice(0, 4).map(([t]) => t);
      const first = items[0]!;
      const sorted = [...items].sort((a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime());
      const titleCore = common.length ? common.join(' ') : first.categoryLabel ?? 'incidents';
      const suggestedTitle = `Recurring ${first.categoryLabel ? `${first.categoryLabel.toLowerCase()} ` : ''}incidents${first.ciName ? ` on ${first.ciName}` : ''}: ${titleCore} (${first.customerName})`.slice(0, 120);
      clusters.push({
        key: `${gk}|${sorted[0]!.id}`,
        customerId: first.customerId,
        customerName: first.customerName,
        categoryLabel: first.categoryLabel,
        ciName: first.ciName,
        serviceName: first.serviceName,
        count: items.length,
        openCount: items.filter((i) => ['new', 'open', 'pending'].includes(i.statusCategory)).length,
        firstAt: new Date(sorted[sorted.length - 1]!.createdAt).toISOString(),
        lastAt: new Date(sorted[0]!.createdAt).toISOString(),
        commonTerms: common,
        suggestedTitle,
        sampleTickets: sorted.slice(0, 5).map((i) => ({ id: i.id, number: i.number, title: i.title, status: i.status, createdAt: new Date(i.createdAt).toISOString(), link: ticketLink(ctx, i.id) })),
      });
    }
  }
  clusters.sort((a, b) => b.count - a.count || b.lastAt.localeCompare(a.lastAt));
  return { days, minCount, rows, top: clusters.slice(0, 40) };
}

