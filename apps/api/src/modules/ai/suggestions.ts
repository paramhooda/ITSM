// ---------------------------------------------------------------- duplicate check

export const duplicateCheck = (who: Who, ticketId: string) => asSteps(who).tx((ctx) => duplicateCheckIn(ctx, ticketId));

async function duplicateCheckIn(ctx: Ctx, ticketId: string) {
  await assertFeature(ctx, 'duplicates');
  const { row } = await readTicket(ctx, ticketId);
  const conds = [sql`x.id <> ${row.id}::uuid`, sql`x.customer_id = ${row.customerId}::uuid`, sql`x.type = ${row.type}`, sql`s.status_category IN ('new','open','pending')`];
  if (!isCustomerUser(ctx) && !ctx.can('soc:read')) conds.push(sql`x.domain <> 'soc'`);
  const res = await ctx.tx.execute(sql`
    SELECT x.id, x.number, x.title, x.type, x.created_at AS "createdAt", s.label AS "status", x.primary_ci_id AS "primaryCiId",
           similarity(x.title, ${row.title}) AS "titleSimilarity",
           ts_rank(x.search_vector, plainto_tsquery('simple', ${row.title})) AS "rank",
           (x.primary_ci_id IS NOT NULL AND x.primary_ci_id = ${row.primaryCiId ?? null}::uuid) AS "sameCi",
           EXISTS (SELECT 1 FROM ticket_cis a JOIN ticket_cis b ON a.ci_id = b.ci_id WHERE a.ticket_id = x.id AND b.ticket_id = ${row.id}::uuid) AS "sharesCi"
    FROM tickets x JOIN config_options s ON s.id = x.status_id
    WHERE ${sql.join(conds, sql` AND `)}
      AND (similarity(x.title, ${row.title}) > 0.3 OR x.search_vector @@ plainto_tsquery('simple', ${row.title})
           OR (x.primary_ci_id IS NOT NULL AND x.primary_ci_id = ${row.primaryCiId ?? null}::uuid)
           OR EXISTS (SELECT 1 FROM ticket_cis a JOIN ticket_cis b ON a.ci_id = b.ci_id WHERE a.ticket_id = x.id AND b.ticket_id = ${row.id}::uuid))
    ORDER BY similarity(x.title, ${row.title}) DESC, x.created_at DESC
    LIMIT 10`);
  const rows = res.rows as { id: string; number: string; title: string; type: string; createdAt: Date | string; status: string; titleSimilarity: number; rank: number; sameCi: boolean; sharesCi: boolean }[];
  const items = rows
    .map((r) => {
      const ageDays = (Date.now() - new Date(r.createdAt).getTime()) / 86_400_000;
      const score = Math.min(1, Number(r.titleSimilarity) * 0.6 + Math.min(Number(r.rank), 0.5) * 0.4 + (r.sameCi ? 0.3 : r.sharesCi ? 0.2 : 0) + (ageDays <= 7 ? 0.1 : 0));
      const reasons = [Number(r.titleSimilarity) > 0.3 ? `title ${Math.round(Number(r.titleSimilarity) * 100)}% similar` : null, r.sameCi ? 'same primary CI' : r.sharesCi ? 'shares an affected CI' : null, ageDays <= 7 ? 'opened in the last 7 days' : null].filter(Boolean) as string[];
      return { id: r.id, number: r.number, title: r.title, type: r.type, status: r.status, createdAt: new Date(r.createdAt).toISOString(), score: Math.round(score * 100) / 100, reasons, link: ticketLink(ctx, r.id) };
    })
    .filter((i) => i.score >= 0.25)
    .sort((a, b) => b.score - a.score);
  const payload = { items, likely: items.filter((i) => i.score >= 0.6).map((i) => i.number) };
  const suggestionId = await store(ctx, { customerId: row.customerId, entityType: 'ticket', entityId: row.id, kind: 'duplicates', payload, rationale: 'Open tickets of the same customer with similar titles or shared configuration items', confidence: items[0] ? Math.round(items[0].score * 100) : 0 });
  return { suggestionId, aiGenerated: false, ...payload };
}

