/**
 * AI-assisted ITSM features. Every result is stored as an `ai_suggestions`
 * row (status proposed) and applied only when a human accepts it through the
 * normal ticket endpoints. Each feature has a deterministic fallback used when
 * no provider is configured, so the UI always gets a sane structure.
 *
 * Each feature runs as gather → model → store: the database work happens in
 * short steps (`Steps.tx`) and the model call in between holds no connection.
 * Called with a plain `Ctx` (tests, tools) the steps share that ctx's
 * transaction instead.
 */
type Who = Ctx | Steps;

const trunc = (s: string | null | undefined, n: number) => (s ? (s.length > n ? `${s.slice(0, n)}…` : s) : '');
const firstName = (name?: string | null) => (name ? name.split(/\s+/)[0]! : '');
const minutesLabel = (m: number) => (Math.abs(m) >= 120 ? `${Math.round(Math.abs(m) / 60)}h` : `${Math.abs(m)}m`);

export type SuggestionKind = 'summary' | 'classification' | 'assignment' | 'similar' | 'knowledge' | 'resolution' | 'draft_update' | 'duplicates' | 'change_impact' | 'problem_cluster';

async function store(ctx: Ctx, input: { customerId: string | null; entityType: string; entityId: string; kind: SuggestionKind; payload: Record<string, unknown>; rationale?: string | null; confidence?: number | null }) {
  const [row] = await ctx.tx
    .insert(schema.aiSuggestions)
    .values({ customerId: input.customerId, entityType: input.entityType, entityId: input.entityId, kind: input.kind, payload: input.payload, rationale: input.rationale ?? null, confidence: input.confidence ?? null, status: 'proposed' })
    .returning({ id: schema.aiSuggestions.id });
  return row!.id;
}

async function readTicket(ctx: Ctx, id: string) {
  const row = await loadTicket(ctx, id);
  ctx.require(isCustomerUser(ctx) ? 'portal:tickets' : 'tickets:read', row.customerId);
  const detail = await getTicket(ctx, id);
  return { row, detail };
}

// ---------------------------------------------------------------- summarize

const summarySchema = z.object({ summary: z.string().min(1).max(2000), keyFacts: z.array(z.string().max(300)).max(10), nextSteps: z.array(z.string().max(300)).max(8) });

export async function summarize(who: Who, ticketId: string) {
  const s = asSteps(who);
  const g = await s.tx(async (ctx) => {
    await assertFeature(ctx, 'summarize');
    const { row, detail } = await readTicket(ctx, ticketId);
    const tl = await timeline(ctx, ticketId);
    return { row, detail, items: tl.items, compact: compactDetail(ctx, detail), recent: compactTimeline(tl.items, 12) };
  });
  const llm = await llmJson(SUMMARIZE_SYSTEM, JSON.stringify({ ticket: g.compact, timeline: g.recent }), (v) => summarySchema.parse(v));
  const payload = llm?.data ?? fallbackSummary(g.detail, g.items);
  return s.tx(async (ctx) => {
    const suggestionId = await store(ctx, { customerId: g.row.customerId, entityType: 'ticket', entityId: g.row.id, kind: 'summary', payload, rationale: llm ? 'Generated by the AI provider from the ticket and its timeline' : 'Rule-based summary (AI provider not configured)' });
    return { suggestionId, aiGenerated: !!llm, ...payload };
  });
}

type Detail = Awaited<ReturnType<typeof getTicket>>;
type TimelineItems = Awaited<ReturnType<typeof timeline>>['items'];

function fallbackSummary(d: Detail, items: TimelineItems): z.infer<typeof summarySchema> {
  const worst = d.sla;
  const owner = d.assignee?.name ? `${d.assignee.name}${d.team ? ` (${d.team.name})` : ''}` : d.team?.name ?? 'nobody yet';
  const summary = `${d.number} is a ${d.priority?.label ?? 'unprioritised'} ${d.typeLabel.toLowerCase()} for ${d.customer?.name ?? 'an unknown customer'}: "${d.title}". It is ${d.status?.label?.toLowerCase() ?? 'in an unknown state'} and assigned to ${owner}.${worst ? ` The ${worst.metric} SLA is ${worst.breached ? 'breached' : worst.paused ? 'paused' : `running (${worst.pctConsumed}% consumed, ${worst.remainingMinutes >= 0 ? `${minutesLabel(worst.remainingMinutes)} left` : `${minutesLabel(worst.remainingMinutes)} overdue`})`}.` : ''}`;
  const keyFacts: string[] = [];
  keyFacts.push(`Opened ${d.createdAt.toISOString().slice(0, 16).replace('T', ' ')} UTC${d.createdByUser ? ` by ${d.createdByUser.name}` : ''}`);
  if (d.site?.name || d.service?.name) keyFacts.push([d.site?.name ? `Site: ${d.site.name}` : null, d.service?.name ? `Service: ${d.service.name}` : null].filter(Boolean).join(' · '));
  if (d.category?.label) keyFacts.push(`Category: ${d.category.label}${d.subcategory?.label ? ` / ${d.subcategory.label}` : ''}`);
  if (d.cis.length) keyFacts.push(`Affected CIs: ${d.cis.map((c) => c.name).join(', ')}`);
  keyFacts.push(`Scope: ${d.scopeStatus.replace(/_/g, ' ')}${d.contract ? ` (${d.contract.number})` : ''}`);
  if (d.isMajor) keyFacts.push('Flagged as a major incident');
  if (d.escalationLevel > 0) keyFacts.push(`Escalated to level ${d.escalationLevel}`);
  const comments = items.filter((i) => i.kind === 'comment').slice(-3);
  for (const c of comments) keyFacts.push(`${c.isInternal ? 'Work note' : 'Comment'} by ${c.actorName ?? 'unknown'}: ${trunc(c.body?.replace(/\s+/g, ' '), 140)}`);
  if (d.resolutionNotes) keyFacts.push(`Resolution: ${trunc(d.resolutionNotes.replace(/\s+/g, ' '), 160)}`);
  const nextSteps: string[] = [];
  const cat = d.status?.category;
  if (cat === 'resolved') nextSteps.push('Confirm the fix with the requester and close the ticket');
  else if (cat === 'closed' || cat === 'cancelled') nextSteps.push('No action required');
  else {
    if (!d.assigneeId) nextSteps.push('Assign an owner (engineer or team)');
    if (!d.firstResponseAt) nextSteps.push('Send a first response to the requester');
    if (worst && (worst.breached || worst.pctConsumed >= 75)) nextSteps.push(`Prioritise: ${worst.metric} SLA ${worst.breached ? 'is breached' : `due in ${minutesLabel(worst.remainingMinutes)}`}`);
    if (cat === 'pending') nextSteps.push('Follow up on the pending item (customer / vendor) and resume work');
    if (!d.category) nextSteps.push('Set a category to improve routing and reporting');
    if (!nextSteps.length) nextSteps.push('Continue diagnosis and post a progress update');
  }
  return { summary, keyFacts: keyFacts.slice(0, 8), nextSteps: nextSteps.slice(0, 5) };
}

