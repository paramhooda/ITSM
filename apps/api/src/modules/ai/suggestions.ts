/** Phrases and words ending in "!" count double (strong signal). */
const HIGH_IMPACT = ['all users', 'everyone', 'entire!', 'whole site', 'site down', 'outage!', 'multiple users', 'several users', 'many users', 'department', 'company-wide', 'production!', 'all sites', 'business stopped', 'team'];
const LOW_IMPACT = ['one user', 'single user', 'my laptop', 'my account', 'my pc', 'only me', 'cosmetic!'];
const HIGH_URGENCY = ['urgent!', 'immediately!', 'asap!', 'critical!', 'outage!', 'down', 'not working', 'stopped', 'cannot work', 'emergency!', 'p1!', 'major!', 'clicked the link'];
const LOW_URGENCY = ['when possible', 'no rush', 'low priority', 'whenever!', 'nice to have', 'planning!', 'question'];

function scoreKeywords(text: string, words: string[]) {
  let score = 0;
  for (const raw of words) {
    const strong = raw.endsWith('!');
    const w = strong ? raw.slice(0, -1) : raw;
    if (text.includes(w)) score += strong || w.includes(' ') ? 2 : 1;
  }
  return score;
}

/** Crude stemmer so "failed" / "failure" / "failing" match a "Job Failure" label. */
const stem = (w: string) => w.toLowerCase().replace(/(ing|ures?|ed|es|s)$/, '');
const textStems = (text: string) => new Set(text.toLowerCase().split(/[^a-z0-9]+/).filter((w) => w.length > 2).map(stem));
/** Fraction of the label's significant words whose stem appears in the text (0..1), weighted ×2 to be comparable with phrase hits. */
function scoreLabel(stems: Set<string>, label: string) {
  const words = label.toLowerCase().split(/[^a-z0-9]+/).filter((w) => w.length > 2 && !['and', 'the', 'for'].includes(w));
  if (!words.length) return 0;
  const hits = words.filter((w) => stems.has(stem(w))).length;
  return hits === words.length ? 2 : hits > 0 ? hits / words.length : 0;
}

async function priorityFromMatrix(ctx: Ctx, impactId: string | null, urgencyId: string | null) {
  if (!impactId || !urgencyId) return null;
  const [cell] = await ctx.tx.select().from(schema.priorityMatrix).where(and(eq(schema.priorityMatrix.impactId, impactId), eq(schema.priorityMatrix.urgencyId, urgencyId))).limit(1);
  return cell ? await optionById(ctx.tx, cell.priorityId) : null;
}

type ClassifyInput = { title: string; description?: string | null; type?: string | null; domainHint?: string | null };
type Gathered = Awaited<ReturnType<typeof gatherClassification>>;

/** Step 1 (database): the option lists and the deterministic heuristic, which is also the fallback. */
async function gatherClassification(ctx: Ctx, input: ClassifyInput) {
  const [categories, subcategories, impacts, urgencies, priorities] = await Promise.all([optionsOfType(ctx.tx, 'ticket_category'), optionsOfType(ctx.tx, 'ticket_subcategory'), optionsOfType(ctx.tx, 'ticket_impact'), optionsOfType(ctx.tx, 'ticket_urgency'), optionsOfType(ctx.tx, 'ticket_priority')]);
  const active = (o: OptionRow) => o.isActive;
  const cats = categories.filter(active);
  const subs = subcategories.filter(active);
  const text = `${input.title}\n${input.description ?? ''}`.toLowerCase();

  // deterministic heuristic first (also the fallback)
  const scored = cats
    .map((c) => ({ c, score: scoreKeywords(text, [...(KEYWORDS[c.key] ?? []), c.label.toLowerCase()]) + (input.domainHint && c.domain === input.domainHint ? 0.5 : 0) }))
    .sort((a, b) => b.score - a.score);
  const bestCat = scored[0] && scored[0].score > 0 ? scored[0].c : null;
  const stems = textStems(text);
  const sub = bestCat ? subs.filter((s) => s.parentId === bestCat.id).map((s) => ({ s, score: scoreKeywords(text, [s.label.toLowerCase()]) + scoreLabel(stems, s.label) })).sort((a, b) => b.score - a.score)[0] : undefined;
  const bestSub = sub && sub.score >= 1 ? sub.s : null;
  const impactScore = scoreKeywords(text, HIGH_IMPACT) - scoreKeywords(text, LOW_IMPACT);
  const urgencyScore = scoreKeywords(text, HIGH_URGENCY) - scoreKeywords(text, LOW_URGENCY);
  const pickLevel = (opts: OptionRow[], s: number) => {
    const act = opts.filter(active).sort((a, b) => (a.level ?? 0) - (b.level ?? 0));
    if (!act.length) return null;
    if (s >= 2) return act[0]!;
    if (s <= -1) return act[act.length - 1]!;
    return act.find((o) => o.isDefault) ?? act[Math.floor(act.length / 2)]!;
  };
  const impact = pickLevel(impacts, impactScore);
  const urgency = pickLevel(urgencies, urgencyScore);
  const matrixPriority = await priorityFromMatrix(ctx, impact?.id ?? null, urgency?.id ?? null);
  const priority = matrixPriority ?? priorities.find((p) => p.isDefault && p.isActive) ?? null;
  const heuristic: Classification = {
    categoryKey: bestCat?.key ?? null,
    subcategoryKey: bestSub?.key ?? null,
    impactKey: impact?.key ?? null,
    urgencyKey: urgency?.key ?? null,
    priorityKey: priority?.key ?? null,
    confidence: Math.min(90, 35 + (scored[0]?.score ?? 0) * 12 + (bestSub ? 10 : 0)),
    rationale: bestCat ? `Keywords match "${bestCat.label}"${bestSub ? ` / ${bestSub.label}` : ''}; impact ${impact?.key ?? '-'} × urgency ${urgency?.key ?? '-'} → ${priority?.label ?? 'default priority'} from the priority matrix.` : 'No category keywords matched; priority inputs default to medium.',
    categoryId: bestCat?.id ?? null,
    subcategoryId: bestSub?.id ?? null,
    impactId: impact?.id ?? null,
    urgencyId: urgency?.id ?? null,
    priorityId: priority?.id ?? null,
    labels: { category: bestCat?.label ?? null, subcategory: bestSub?.label ?? null, impact: impact?.label ?? null, urgency: urgency?.label ?? null, priority: priority?.label ?? null },
  };
  const options = {
    categories: cats.map((c) => ({ key: c.key, label: c.label, domain: c.domain, subcategories: subs.filter((s) => s.parentId === c.id).map((s) => ({ key: s.key, label: s.label })) })),
    impact: impacts.filter(active).map((o) => ({ key: o.key, label: o.label })),
    urgency: urgencies.filter(active).map((o) => ({ key: o.key, label: o.label })),
    priority: priorities.filter(active).map((o) => ({ key: o.key, label: o.label })),
  };
  return { input, heuristic, options, cats, subs, impacts, urgencies, priorities, impact, urgency, priority };
}

/** Step 2 (model, no transaction): the provider's pick from the real option keys; null when disabled or unusable. */
async function classifyLlm(g: Gathered) {
  if (!enabled()) return null;
  return llmJson(CLASSIFY_SYSTEM, JSON.stringify({ ticket: { type: g.input.type ?? 'incident', title: g.input.title, description: trunc(g.input.description, 4000) }, options: g.options }), (v) => classificationSchema.parse(v), { maxTokens: 400 });
}

/** Step 3 (database): resolve the model's keys against the options and the priority matrix, or keep the heuristic. */
async function finishClassification(ctx: Ctx, g: Gathered, llm: Awaited<ReturnType<typeof classifyLlm>>): Promise<{ result: Classification; aiGenerated: boolean }> {
  if (!llm) return { result: g.heuristic, aiGenerated: false };
  const { cats, subs, impacts, urgencies, priorities } = g;
  const cat = cats.find((c) => c.key === llm.data.categoryKey) ?? null;
  const subc = cat ? subs.find((s) => s.parentId === cat.id && s.key === llm.data.subcategoryKey) ?? null : null;
  const imp = impacts.find((o) => o.key === llm.data.impactKey && o.isActive) ?? g.impact;
  const urg = urgencies.find((o) => o.key === llm.data.urgencyKey && o.isActive) ?? g.urgency;
  const prio = (await priorityFromMatrix(ctx, imp?.id ?? null, urg?.id ?? null)) ?? priorities.find((p) => p.key === llm.data.priorityKey && p.isActive) ?? g.priority;
  return {
    aiGenerated: true,
    result: {
      categoryKey: cat?.key ?? null,
      subcategoryKey: subc?.key ?? null,
      impactKey: imp?.key ?? null,
      urgencyKey: urg?.key ?? null,
      priorityKey: prio?.key ?? null,
      confidence: Math.round(llm.data.confidence),
      rationale: llm.data.rationale,
      categoryId: cat?.id ?? null,
      subcategoryId: subc?.id ?? null,
      impactId: imp?.id ?? null,
      urgencyId: urg?.id ?? null,
      priorityId: prio?.id ?? null,
      labels: { category: cat?.label ?? null, subcategory: subc?.label ?? null, impact: imp?.label ?? null, urgency: urg?.label ?? null, priority: prio?.label ?? null },
    },
  };
}

export async function classify(who: Who, ticketId: string) {
  const s = asSteps(who);
  const g = await s.tx(async (ctx) => {
    await assertFeature(ctx, 'classify');
    const { row, detail } = await readTicket(ctx, ticketId);
    return { row, gathered: await gatherClassification(ctx, { title: row.title, description: row.description, type: row.type, domainHint: detail.service?.key ? null : row.domain }) };
  });
  const llm = await classifyLlm(g.gathered);
  return s.tx(async (ctx) => {
    const { result, aiGenerated } = await finishClassification(ctx, g.gathered, llm);
    const { row } = g;
    const suggestionId = await store(ctx, { customerId: row.customerId, entityType: 'ticket', entityId: row.id, kind: 'classification', payload: result as unknown as Record<string, unknown>, rationale: result.rationale, confidence: result.confidence });
    return { suggestionId, aiGenerated, current: { categoryId: row.categoryId, subcategoryId: row.subcategoryId, impactId: row.impactId, urgencyId: row.urgencyId, priorityId: row.priorityId }, ...result };
  });
}

/** Classification for a ticket that does not exist yet (create form). Nothing is stored. */
export async function classifyDraft(who: Who, input: { title: string; description?: string | null; customerId?: string; type?: string }) {
  const s = asSteps(who);
  const g = await s.tx(async (ctx) => {
    await assertFeature(ctx, 'classify');
    if (input.customerId) ctx.requireCustomer(input.customerId);
    return gatherClassification(ctx, { title: input.title, description: input.description, type: input.type });
  });
  const llm = await classifyLlm(g);
  return s.tx(async (ctx) => {
    const { result, aiGenerated } = await finishClassification(ctx, g, llm);
    return { aiGenerated, ...result };
  });
}

