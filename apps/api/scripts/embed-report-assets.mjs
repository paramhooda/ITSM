/**
 * Embeds the report document's binary assets as TypeScript string constants.
 * The API is bundled by esbuild and the runtime image copies only `dist`, so a
 * PNG or font on disk would not ship; the wordmark and the latin variable font
 * travel inside the module instead. Run `npm run assets:reports` after the logo
 * changes and commit the output.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const logoPath = fileURLToPath(new URL('../../web/public/logo.png', import.meta.url));
const fontPath = fileURLToPath(new URL('../../../node_modules/@fontsource-variable/geist/files/geist-latin-wght-normal.woff2', import.meta.url));
const outPath = fileURLToPath(new URL('../src/modules/reports/theme/assets.ts', import.meta.url));

const logo = readFileSync(logoPath);
const font = readFileSync(fontPath);
const out = `/** Generated by apps/api/scripts/embed-report-assets.mjs (npm run assets:reports). Do not edit by hand. */
/** apps/web/public/logo.png (200 x 53): the Progression wordmark printed on covers and the running masthead. */
export const LOGO_PNG_DATA_URI = 'data:image/png;base64,${logo.toString('base64')}';
/** Geist Variable, latin subset, weights 100-900 (the application typeface), embedded so Chromium prints with it. */
export const GEIST_WOFF2_DATA_URI = 'data:font/woff2;base64,${font.toString('base64')}';
export const LOGO_ASPECT = 200 / 53;
`;
writeFileSync(outPath, out);
console.log(`logo ${logo.length} bytes, font ${font.length} bytes -> ${outPath} (${out.length} characters)`);
